def render(ops, n):
    global N
    N = n
    g = [[0] * n for _ in range(n)]
    for j in range(n):
        for i in range(n):
            px, py = (i + .5) / n, (j + .5) / n
            for sh, c in ops:
                if sh(px, py): g[j][i] = c
    return g

def rows(g): return "/".join("".join("." if v == 0 else chr(96 + v) for v in r) for r in g)

