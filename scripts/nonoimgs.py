import math, json, sys
N = 10
class S:
    def __init__(s, f): s.f = f
    def __call__(s, x, y): return s.f(x, y)
    def __and__(a, b): return S(lambda x, y: a(x, y) and b(x, y))
    def __or__(a, b): return S(lambda x, y: a(x, y) or b(x, y))
    def __sub__(a, b): return S(lambda x, y: a(x, y) and not b(x, y))
    def mir(a): return S(lambda x, y: a(x, y) or a(1 - x, y))
def E(cx, cy, rx, ry): return S(lambda x, y: ((x - cx) / max(rx, 1e-9)) ** 2 + ((y - cy) / max(ry, 1e-9)) ** 2 <= 1)
def C(cx, cy, r): return E(cx, cy, r, r)
def R(x0, y0, x1, y1): return S(lambda x, y: x0 <= x <= x1 and y0 <= y <= y1)
def P(*pts):
    def f(x, y):
        c = False; n = len(pts)
        for i in range(n):
            x1, y1 = pts[i]; x2, y2 = pts[(i + 1) % n]
            if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1: c = not c
        return c
    return S(f)
def L(x0, y0, x1, y1, w):
    def f(x, y):
        dx, dy = x1 - x0, y1 - y0; l2 = dx * dx + dy * dy
        t = 0 if l2 == 0 else max(0, min(1, ((x - x0) * dx + (y - y0) * dy) / l2))
        return math.hypot(x - (x0 + t * dx), y - (y0 + t * dy)) <= w / 2
    return S(f)
def D(x, y):
    return S(lambda px, py: abs(px - (math.floor(x * N) + .5) / N) < .5 / N and abs(py - (math.floor(y * N) + .5) / N) < .5 / N)
def DD(*pts):
    s = D(*pts[0])
    for p in pts[1:]: s = s | D(*p)
    return s
def star(cx, cy, Ro, ri, n=5, rot=-90):
    pts = []
    for i in range(2 * n):
        a = math.radians(rot + i * 180 / n); r = Ro if i % 2 == 0 else ri
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return P(*pts)
def ring(cx, cy, r0, r1): return C(cx, cy, r1) - C(cx, cy, r0)
def sector(cx, cy, a0, a1):
    def f(x, y):
        a = math.degrees(math.atan2(y - cy, x - cx)) % 360
        a0m, a1m = a0 % 360, a1 % 360
        return (a0m <= a <= a1m) if a0m <= a1m else (a >= a0m or a <= a1m)
    return S(f)
def rays(cx, cy, r0, r1, n, w, off=0):
    s = None
    for i in range(n):
        a = math.radians(off + i * 360 / n)
        l = L(cx + r0 * math.cos(a), cy + r0 * math.sin(a), cx + r1 * math.cos(a), cy + r1 * math.sin(a), w)
        s = l if s is None else s | l
    return s

